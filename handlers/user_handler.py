"""
Обработчик личного чата пользователя.
Здесь отправляется красивая информация о службе поддержки и рекламе.
"""

import logging

from aiogram import Router, F
from aiogram.filters import CommandStart
from aiogram.types import Message

logger = logging.getLogger(__name__)
router = Router()

SUPPORT_MESSAGE = (
    "📌 <b>Связь со службой поддержки</b>\n"
    "────────────────────────────\n"
    "Если у вас есть вопросы, претензии или нужна помощь,\n"
    "напишите нам — мы всегда на связи.\n\n"
    "💬 <b>Как обратиться:</b>\n"
    "• Напишите своё обращение прямо сюда\n"
    "• Опишите, что случилось\n"
    "• Мы ответим в ближайшее время\n\n"
    "📣 <b>По рекламе</b>\n"
    "Рекламные предложения и коммерческие вопросы принимаются здесь.\n"
    "Укажите свой проект, бюджет и желаемый формат —\n"
    "и мы подберем лучшее решение для вас.\n\n"
    "✨ Спасибо, что выбрали нас!"
)


@router.message(CommandStart(), F.chat.type == "private")
async def cmd_start(message: Message) -> None:
    """Приветствие при запуске бота в личном чате."""
    await message.answer(
        "👋 <b>Добро пожаловать!</b>\n\n"
        "Я помогу вам быстро связаться с нашей поддержкой и принять\n"
        "запрос по рекламе.\n\n"
        "Отправьте сообщение, и мы направим его в нужный отдел.\n\n"
        "<b>Что можно написать:</b>\n"
        "• Вопрос по сервису\n"
        "• Жалобу или пожелание\n"
        "• Запрос по рекламе или партнёрству"
    )


@router.message(F.chat.type == "private")
async def handle_private_message(message: Message) -> None:
    """Отвечает на любое личное сообщение поддерживающей карточкой."""
    await message.answer(SUPPORT_MESSAGE)
    logger.info(
        f"Отправлено сообщение поддержки пользователю {message.from_user.id}"
    )
